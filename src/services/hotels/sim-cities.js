function norm(text) {
  return String(text || '').trim().toLowerCase().replace(/\s+/g, '');
}

/** Exact lookup by name / '杭州市' / alias / code; no fuzzy matching. */
export function findCity(text, cities = CITIES) {
  const q = norm(text);
  if (!q) return null;
  const bare = q.endsWith('市') ? q.slice(0, -1) : q;
  return cities.find((c) => c.name === bare || c.fullName === q || c.code === q || c.aliases.some((a) => a.toLowerCase() === q)) || null;
}

export function findCityByCode(code, cities = CITIES) {
  return cities.find((c) => c.code === code) || null;
}

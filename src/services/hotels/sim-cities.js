/**
 * Supported cities for the simulated supplier: real 商圈/areas and real landmarks with approximate
 * coordinates in GCJ-02 (the datum of 高德/腾讯 maps; a few hundred meters of accuracy). Hotels generated
 * around these areas are fictional; the places themselves are not.
 *
 * Area fields:
 *  kind      drives the generated hotel mix (see sim-hotels.js)
 *  spreadM   how far generated hotels sit from the area center
 *  bearings  [from, to] degrees clockwise from north where hotels may be placed (keeps them out of
 *            lakes and the sea); may exceed 360 to wrap around north
 *  features  tags/amenity hints: subway lake river (a big 江) canal (a 河/canal: 河景, never 江景) sea
 *            mountain family night quiet oldtown station airport carfree (no cars: no parking)
 *  priceLevel  optional city price factor within its tier (北京/上海 above 广州/深圳 …), default 1
 * Landmark extentM: distances to big places (西湖, 亚龙湾) are measured from roughly their edge.
 * Landmark district: only when it differs from its area's district (广州塔 is in 海珠区, not 天河区).
 */

/** extentM: rough radius of an extended place (lake, beach, park), so distances are measured from its edge. */
function L(name, type, lng, lat, aliases = [], extentM = 0, district) {
  return { name, type, location: { lng, lat }, aliases, extentM, ...(district ? { district } : {}) };
}

function A(name, district, kind, [lng, lat], { aliases = [], short, spreadM, bearings, features = [], reason, landmarks }) {
  return { name, aliases, short: short || name.split(/[/·]/)[0], district, kind, center: { lng, lat }, spreadM, bearings, features, reason, landmarks };
}

